def test_gev_smalln_cp_quantiles_clamped_to_support():
    """Phase 4 (Issue 4): the GEV CP quantiles are clamped to the support.

    At small n the DMGS expansion can push a CP quantile outside the GEV
    support (e.g. a negative 1-in-100 return level for a positive-support fit).
    The core now clamps to the support bound (the reference `fixgevrange`) and
    falls back to the MLE quantile when a CP quantile still leaves the support.

    The `y_smalln_clamp` dataset (n = 20) is the defect case: its raw DMGS CP
    quantile at p = 0.99 exceeds `ml_max`, so the clamp is genuinely exercised.
    """
    y = np.array([
        1.27, 1.37, 1.57, 1.91, 1.20, 1.90, 1.94, 1.66, 1.63, 1.06,
        1.21, 1.18, 1.69, 1.38, 1.77, 1.50, 1.72, 1.99, 1.38, 1.78,
    ])
    p = np.array([0.1, 0.25, 0.5, 0.75, 0.9, 0.99])
    res = rusty_fitdistcp.ppf_gev(y, p)
    _check_common(res)

    # The fitted shape is negative => finite upper support bound `ml_max`.
    assert res["ml_params"][2] < 0.0
    ml_max = float(res["ml_max"])
    assert np.isfinite(ml_max)

    # Every CP quantile is finite and within the support.
    cp_q = np.asarray(res["cp_quantiles"])
    assert np.all(np.isfinite(cp_q))
    assert np.all(cp_q <= ml_max + 1e-9)

    # The 1-in-100 return level (p = 0.99) is finite, within support, and
    # non-negative (the Issue 4 defect was a negative return level).
    q100 = float(cp_q[-1])
    assert np.isfinite(q100)
    assert q100 >= 0.0
    assert q100 <= ml_max + 1e-9


def test_gev_short_record_fit_is_robust():
    """Phase 3 (Issue 3): the ML optimiser is robust on short records.

    The hand-rolled BFGS lacked the reference's multi-start / init strategy, so
    on short (hail-region-shaped) records it stopped at a worse fit. The core
    now seeds from `setics`-style heuristics, adds a Nelder-Mead polish, and
    keeps the best log-likelihood, so the fit is init-independent and no region
    returns NaN.

    The reference log-likelihoods for these three fixed short records are
    pinned in `tests/golden/short_record_golden.json` (generated by
    `tools/generate_short_record_golden.R`).
    """
    # The three fixed short-record datasets from the Phase 3 fixture.
    datasets = [
        np.array([1.12, 1.48, 1.21, 1.77, 1.05, 1.63, 1.34, 1.19, 1.88, 1.27, 1.55, 1.41]),
        np.array([1.31, 1.62, 1.44, 1.90, 1.22, 1.71, 1.53, 1.38, 1.84, 1.47]),
        np.array([1.08, 1.55, 1.29, 1.83, 1.14, 1.68, 1.42, 1.24, 1.96, 1.36,
                  1.51, 1.19, 1.74, 1.33, 1.60]),
    ]
    # The reference `optim` log-likelihoods (from the fixture).
    ref_loglik = [0.028180876895080587, 1.5306520020982421, -0.35163134090244857]
    p = np.array([0.1, 0.25, 0.5, 0.75, 0.9, 0.99])

    for y, ref_ll in zip(datasets, ref_loglik):
        assert 10 <= y.size <= 15
        res = rusty_fitdistcp.ppf_gev(y, p)
        _check_common(res)

        # No NaN: every fitted parameter and CP quantile is finite.
        assert np.all(np.isfinite(res["ml_params"]))
        assert np.all(np.isfinite(res["cp_quantiles"]))

        # The fitted log-likelihood matches the reference (the objective is
        # well-determined at the optimum).
        assert abs(res["ml_value"] - ref_ll) <= 1e-6 + 1e-6 * abs(ref_ll)


