#!/usr/bin/env python3
"""W21 packaging helper — inject `@inheritParams fitdistcp_params` into the
extendr-generated R wrappers.

The `d/p/q/r/t***_cp` wrappers share the same argument documentation, which is
defined once in `R/fitdistcp-params.R`. This script adds
`@inheritParams fitdistcp_params` to every exported wrapper so `R CMD check`
does not warn about undocumented arguments.

It edits ONLY the generated R wrapper file (an R-package file); the Rust
binding crate source is left untouched (packaging-only change). If the wrappers
are ever regenerated by extendr, re-run this script afterwards.

Run from the repository root:
  python3 tools/inject-param-docs.py
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
WRAPPERS = REPO / "crates/fitdistcp-r/R/extendr-wrappers.R"

MARKER = "@inheritParams fitdistcp_params"

# Functions that should NOT get the shared params (they have no shared args),
# but which ARE still exported.
NO_PARAMS = {"core_version"}


# extendr marks unused Rust parameters with a leading underscore, which forces
# backtick-quoted R argument names (`_n`, `_x`, ...). R CMD check's \usage
# consistency check then reports them as undocumented. Rename them to the
# reference package's plain names (n, x, t, t0, n0, method); the `.Call` is
# positional so the rename is behaviour-preserving.
RENAME = {
    "`_n`": "n",
    "`_x`": "x",
    "`_t`": "t",
    "`_t0`": "t0",
    "`_n0`": "n0",
    "`_method`": "method",
}


def inject_wrappers(text: str) -> str:
    """Insert `#' @inheritParams ...` / `#' @export` and de-backtick args."""
    lines = text.splitlines()
    out = []
    for line in lines:
        m = re.match(r"^(\w+)\s*<-\s*function", line)
        if m:
            name = m.group(1)
            prev = out[-1] if out else ""
            if name not in NO_PARAMS and MARKER not in prev:
                out.append(f"#' {MARKER}")
            # `@export` so roxygen2 regenerates the NAMESPACE export() lines
            # (the wrappers are the package's public API).
            if "@export" not in prev:
                out.append("#' @export")
        # Only rewrite wrapper definition lines (contain `.Call(`).
        if ".Call(" in line:
            for old, new in RENAME.items():
                line = line.replace(old, new)
        out.append(line)
    return "\n".join(out) + ("\n" if text.endswith("\n") else "")


def main() -> int:
    text = WRAPPERS.read_text()
    new = inject_wrappers(text)
    if new != text:
        WRAPPERS.write_text(new)
        print(f"updated {WRAPPERS.relative_to(REPO)}")
    else:
        print(f"unchanged {WRAPPERS.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
