#!/usr/bin/env bash
#
# W21 packaging helper — assemble a self-contained Rust source tree for the R
# package so that `R CMD build` produces a tarball that builds in isolation
# (CRAN policy; design §11 "Follow rextendr CRAN guidance; vendor crates").
#
# What it does:
#   1. Copies `crates/fitdistcp-core` into
#      `crates/fitdistcp-r/src/rust/fitdistcp-core/` with a *standalone*
#      Cargo.toml (no `workspace = true` inheritance), so the R crate's path
#      dependency resolves inside the tarball.
#   2. Runs `cargo vendor` for the R crate into
#      `crates/fitdistcp-r/src/rust/vendor/` and writes
#      `crates/fitdistcp-r/src/rust/.cargo/config.toml` pointing at it.
#
# The vendored tree is large (~110 MB) and is therefore NOT committed; it is
# regenerated by this script (and by the package `configure` script) whenever a
# tarball is built. Run this from the repository root inside the dev container:
#
#   docker compose run --rm dev bash tools/vendor-r-crate.sh
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CORE_SRC="${REPO_ROOT}/crates/fitdistcp-core"
R_RUST="${REPO_ROOT}/crates/fitdistcp-r/src/rust"
VENDOR_CORE="${R_RUST}/fitdistcp-core"
VENDOR_DIR="${R_RUST}/vendor"
CARGO_CFG_DIR="${R_RUST}/.cargo"

echo "==> Vendoring core crate into ${VENDOR_CORE}"
rm -rf "${VENDOR_CORE}"
mkdir -p "${VENDOR_CORE}"
# Copy only the library sources + manifest; skip tests/benches (not needed to
# build the R package and they would bloat the tarball).
cp -R "${CORE_SRC}/src" "${VENDOR_CORE}/src"
cp "${CORE_SRC}/Cargo.toml" "${VENDOR_CORE}/Cargo.toml"

# Rewrite the core manifest to be standalone: replace every `workspace = true`
# inheritance with an explicit value and drop the dev-only bench targets.
python3 - "${VENDOR_CORE}/Cargo.toml" <<'PY'
import re, sys
path = sys.argv[1]
text = open(path).read()

# Explicit values matching the top-level workspace manifest. Anchor each key to
# the start of a line so `version` does not also match inside `rust-version`.
subs = {
    r'^version\.workspace = true': 'version = "0.1.0"',
    r'^edition\.workspace = true': 'edition = "2021"',
    r'^license\.workspace = true': 'license = "MIT"',
    r'^repository\.workspace = true': 'repository = "https://github.com/stephenjewson/fitdistcp"',
    r'^rust-version\.workspace = true': 'rust-version = "1.85"',
}
for pat, rep in subs.items():
    text = re.sub(pat, rep, text, flags=re.M)

# Replace `{ workspace = true }` dependency specs with explicit versions.
dep_versions = {
    'special': '0.11',
    'statrs': '0.17',
    'nalgebra': '0.33',
    'argmin': '0.10',
    'rayon': '1.10',
    'criterion': '0.5',
    'rand': '0.8',
    'rand_distr': '0.4',
}
for name, ver in dep_versions.items():
    text = re.sub(
        r'^' + re.escape(name) + r'\s*=\s*\{\s*workspace\s*=\s*true\s*\}',
        f'{name} = "{ver}"',
        text, flags=re.M)

# Drop the [dev-dependencies] section and the [[bench]] targets: they are not
# needed to build the R package and would pull criterion/rand into the vendor
# tree.
text = re.split(r'^\[dev-dependencies\]', text, flags=re.M)[0].rstrip() + '\n'

# NOTE: the vendored core crate must NOT declare its own `[workspace]` table —
# it is a plain member of the R crate's workspace (the R crate is the workspace
# root). Adding one here would produce "multiple workspace roots found".

open(path, 'w').write(text)
print("rewrote", path)
PY

echo "==> Running cargo vendor into ${VENDOR_DIR}"
rm -rf "${VENDOR_DIR}" "${CARGO_CFG_DIR}"
mkdir -p "${CARGO_CFG_DIR}"
cargo vendor --manifest-path "${R_RUST}/Cargo.toml" "${VENDOR_DIR}" \
    > "${CARGO_CFG_DIR}/config.toml"

# `cargo vendor` writes an ABSOLUTE path to the vendor directory, which breaks
# the CRAN tarball (it unpacks to a different location). Rewrite it to a path
# relative to the config file's directory (`.cargo/`), i.e. `../vendor`.
cat > "${CARGO_CFG_DIR}/config.toml" <<'CFG'
[source.crates-io]
replace-with = "vendored-sources"

[source.vendored-sources]
# Path is relative to this `.cargo/` directory, so the tarball builds wherever
# it is unpacked.
directory = "../vendor"
CFG

# ---------------------------------------------------------------------------
# Post-process the vendor tree for CRAN portability:
#   * prune test/bench/example/fuzz directories (not needed to build the
#     staticlib) — these contain the >100-byte non-portable paths that
#     `R CMD check` flags (e.g. zerocopy's `output_tests/expected/*.rs`);
#   * rewrite each `.cargo-checksum.json` with an empty `files` map so cargo
#     skips per-file checksum verification (the pruned files would otherwise
#     fail verification). The `package` hash is preserved.
# ---------------------------------------------------------------------------
echo "==> Pruning vendor test/bench/example dirs and rewriting checksums"
python3 - "${VENDOR_DIR}" <<'PY'
import json, os, shutil, sys

vendor = sys.argv[1]
# Directory names pruned wherever they appear in a vendored crate (top level or
# nested under src/). `output_tests` is zerocopy-derive's fixture dir, which
# contains the >100-byte non-portable paths flagged by R CMD check.
prune = {"tests", "test", "benches", "examples", "fuzz", "docs", "doc",
         "output_tests"}
pruned = 0
for crate in sorted(os.listdir(vendor)):
    cdir = os.path.join(vendor, crate)
    if not os.path.isdir(cdir):
        continue
    # Walk the whole crate so nested test/fixture dirs are pruned too.
    for root, dirs, _files in os.walk(cdir, topdown=True):
        for d in list(dirs):
            if d in prune:
                shutil.rmtree(os.path.join(root, d))
                dirs.remove(d)
                pruned += 1
    # Rewrite the checksum file: keep only the package hash.
    cks = os.path.join(cdir, ".cargo-checksum.json")
    if os.path.isfile(cks):
        with open(cks) as fh:
            data = json.load(fh)
        with open(cks, "w") as fh:
            json.dump({"files": {}, "package": data.get("package")}, fh)
print(f"pruned {pruned} directories")
PY

echo "==> Done. Vendored core + $(ls "${VENDOR_DIR}" | wc -l | tr -d ' ') crates."
